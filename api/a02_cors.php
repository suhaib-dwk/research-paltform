// a02_cors.php — رأسيات CORS موحّدة لكل ملفات الـ API
// (Stage A.5: يستبدل التكرار السابق لسطرين ثابتين في كل ملف بمصدر واحد
//  يدعم أصلاً محدداً + بيانات اعتماد، وهو الشرط اللازم لعمل الجلسات PHP
//  عبر الكوكيز — الأصل العام "*" لا يتوافق مطلقاً مع الطلبات المرفقة
//  ببيانات اعتماد (credentials: 'include')، فيرفضها المتصفح صامتاً.)
//
// الاستخدام: require_once('a02_cors.php') في أول كل ملف API، بدل
// السطرين القديمين header('Access-Control-Allow-Origin: *') و ما شابه.
// لا يُستدعى مباشرة كصفحة.
// =====================================================================

// ===== الأصول المسموح بها: بيئة التطوير المحلي (Vite + XAMPP) + الإنتاج =====
// ✅ 5173 هو منفذ Vite الافتراضي، و5200 مستخدَم فعلياً بجلسات عمل أخرى على
// هذا المشروع (قد يشغّله `npm run dev -- --port 5200` أو إعداد محلي مشابه) —
// كلاهما مسموح تفاديًا لالتباس "أعمل على منفذ والـ CORS يسمح بآخر فقط".
$allowedOrigins = [
    'http://localhost:5173',
    'http://localhost:5200',
    'http://localhost',
    'https://ris.sibaljo.com',
];

$origin = $_SERVER['HTTP_ORIGIN'] ?? '';
if (in_array($origin, $allowedOrigins, true)) {
    header('Access-Control-Allow-Origin: ' . $origin);
    header('Access-Control-Allow-Credentials: true');
}
